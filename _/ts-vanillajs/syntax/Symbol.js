//======================================================================================================================
// читаем символ из глобального реестра и записываем его в переменную
id = Symbol.for("id"); // если символа не существует, он будет создан
// читаем его снова и записываем в другую переменную (возможно, из другого места кода)
let idAgain = Symbol.for("id");
// проверяем -- это один и тот же символ
print( id === idAgain ); // true
//======================================================================================================================
// получаем символ по имени
let sym = Symbol.for("name");
let sym2 = Symbol.for("id");
// получаем имя по символу
print( Symbol.keyFor(sym) ); // name
print( Symbol.keyFor(sym2) ); // id
//======================================================================================================================
let globalSymbol = Symbol.for("name");
let localSymbol = Symbol("name");

print( Symbol.keyFor(globalSymbol) ); // name, глобальный символ
print( Symbol.keyFor(localSymbol) ); // undefined для неглобального символа

print( localSymbol.description ); // name
//======================================================================================================================
user = {
  name: "John",
  money: 1000,

  [Symbol.toPrimitive](hint) {
    print(`hint: ${hint}`);
    return hint == "string" ? `{name: "${this.name}"}` : this.money;
  }
};

// демонстрация результатов преобразований:
print(user); // hint: string -> {name: "John"}
print(+user); // hint: number -> 1000
print(user + 500); // hint: default -> 1500
//======================================================================================================================
user = {name: "John"};

print(user); // [object Object]
print(user.valueOf() === user); // true
//======================================================================================================================
user = {
  name: "John",
  money: 1000,

  // для хинта равного "string"
  toString() {
    return `{name: "${this.name}"}`;
  },

  // для хинта равного "number" или "default"
  valueOf() {
    return this.money;
  }

};

print(user); // toString -> {name: "John"}
print(+user); // valueOf -> 1000
print(user + 500); // valueOf -> 1500
//======================================================================================================================
user = {
  name: "John",

  toString() {
    return this.name;
  }
};

print(user); // toString -> John
print(user + 500); // toString -> John500
//======================================================================================================================
let obj = {
  // toString обрабатывает все преобразования в случае отсутствия других методов
  toString() {
    return "2";
  }
};

print(obj * 2); // 4, объект был преобразован к примитиву "2", затем умножение сделало его числом
print(obj + 2); // "22" ("2" + 2), преобразование к примитиву вернуло строку => конкатенация
