// Создаём новый символ - id
let id = Symbol();
//======================================================================================================================
// Создаём символ id с описанием (именем) "id"
id = Symbol("id");
//======================================================================================================================
let id1 = Symbol("id");
let id2 = Symbol("id");
print(id1 == id2); // false
print(id); // TypeError: Cannot convert a Symbol value to a string
print(id.toString()); // Symbol(id), теперь работает
print(id.description); // id
//======================================================================================================================
let user = { name: "Вася" };
