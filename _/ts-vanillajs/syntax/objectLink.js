let a1 = {};
let b1 = a1; // копирование по ссылке
print( a1 == b1 ); // true, обе переменные ссылаются на один и тот же объект
print( a1 === b1 ); // true
//======================================================================================================================
let a2 = {};
let b2 = {}; // два независимых объекта
print( a2 == b2 ); // false
//======================================================================================================================
let user3 = {
  name: "John",
  age: 30
};
let clone3 = {}; // новый пустой объект
// давайте скопируем все свойства user в него
for (let key in user3) {
  clone3[key] = user3[key];
}
// теперь clone это полностью независимый объект с тем же содержимым
clone3.name = "Pete"; // изменим в нём данные
print( user3.name ); // все ещё John в первоначальном объекте
//======================================================================================================================
let user4 = { name: "John" };
let permissions1 = { canView: true };
let permissions2 = { canEdit: true };
// копируем все свойства из permissions1 и permissions2 в user
Object.assign(user4, permissions1, permissions2);
// теперь user = { name: "John", canView: true, canEdit: true }
//======================================================================================================================
let user5 = { name: "John" };
Object.assign(user5, { name: "Pete" });
print(user5.name); // теперь user = { name: "Pete" }
