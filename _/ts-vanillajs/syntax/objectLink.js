//======================================================================================================================
let user7 = {
  name: "John",
  sizes: {
    height: 182,
    width: 50
  }
};
let clone7 = Object.assign({}, user7);
print( user7.sizes === clone7.sizes ); // true, тот же объект
// user и clone обладают общим свойством sizes
user7.sizes.width++;       // изменяем свойства в первом объекте
print(clone7.sizes.width); // 51, видим результат в другом
